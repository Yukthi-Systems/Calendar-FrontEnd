const item = (
  n: number,
  title: string,
  status: Status,
  priority: Priority,
  assigneeIds: string[],
  start: number,
  end: number,
  labels: string[],
  description = '',
  parentId: string | null = null,
  // Who "opened" this task. Defaults to its first assignee (a plausible
  // owner) or you, if it's unassigned — gives the permission demo (creator
  // vs. assignee vs. uninvolved) a natural mix without hand-setting every item.
  createdById: string = assigneeIds[0] ?? CURRENT_USER_ID,
  recurrence: RecurrenceFreq | null = null,
  reminders: Reminder[] = [],
): WorkItem => ({
  id: `YTC-${n}`,
  title,
  description:
    description || `Details for "${title}". Replace with real content later.`,
  status,
  priority,
  assigneeIds,
  createdById,
  parentId,
  start: d(start),
  end: d(end),
  labels,
  recurrence,
  reminders,
});

